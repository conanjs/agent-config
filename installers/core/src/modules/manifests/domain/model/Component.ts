// A component manifest as the installer holds it after reading `component.yaml` (component/v1, data-model "Component").
// Only the fields this release reads are kept, and every list is a fresh immutable copy.
import type { Scope } from '#manifests/domain/model/Slots.ts';

/** A service a component asks the installer to register (privileged, M-01). */
export interface ServiceEntry {
  /** The service kind; only `mcp` exists. */
  readonly kind: string;
  /** The service name. */
  readonly name: string;
  /** The command that starts it. */
  readonly command: string;
  /** Its arguments. */
  readonly args: readonly string[];
}

/** A route: one line that tells an agent when to read which file (privileged, M-01). */
export interface RouteEntry {
  /** The route id. */
  readonly id: string;
  /** Prose: when the route applies. */
  readonly when: string;
  /** The location path the agent reads. */
  readonly read: string;
  /** A location path to read before writing, when the route has one. */
  readonly beforeWriting: string | undefined;
}

/** A hook a component asks the installer to merge into an agent's hook file (privileged, M-01). */
export interface HookEntry {
  /** The hook id. */
  readonly id: string;
  /** The neutral event name. */
  readonly event: string;
  /** The agents it applies to; empty means every agent. */
  readonly agents: readonly string[];
  /** The command, with `{{AGENT_HOME}}` still unresolved. */
  readonly command: string;
  /** The tool matcher, when the hook has one. */
  readonly matcher: string | null | undefined;
}

/** How a variable's value is found by looking, never by running anything (M-18). */
export type DetectRule =
  | { readonly kind: 'env'; readonly name: string }
  | { readonly kind: 'dir-exists'; readonly candidates: readonly string[] };

/** One public variable a component declares (M-08). */
export interface VariableDeclaration {
  /** The upper snake case name. */
  readonly name: string;
  /** What the variable is for. */
  readonly description: string;
  /** Whether install needs a value. */
  readonly required: boolean;
  /** How to propose a value, when the component offers a way. */
  readonly detect: DetectRule | undefined;
}

/** A source another component suggests; shown to V, never fetched (AC-4.5, M-11). */
export type SuggestedSource =
  | { readonly type: 'git'; readonly url: string; readonly ref: string }
  | { readonly type: 'archive'; readonly url: string; readonly sha256: string };

/** What a component needs from a slot. */
export interface SlotDependency {
  /** The slot name. */
  readonly slot: string;
  /** The contract it must offer. */
  readonly contract: string;
  /** Whether install stops without a filler (default false). */
  readonly required: boolean;
  /** The cited docs, generated by `build cite`. */
  readonly docs: readonly string[];
  /** A suggested source, when the component gives one. */
  readonly suggest: SuggestedSource | undefined;
}

/** The surface a component offers. */
export interface Provides {
  /** The contracts it offers, `name/vN`. */
  readonly contracts: readonly string[];
  /** The entry point inside its content. */
  readonly index: string | undefined;
  /** The location paths other components may cite. */
  readonly exports: readonly string[];
  /** The folder of skill sources. */
  readonly skills: string | undefined;
  /** The folder of agent sources. */
  readonly agents: string | undefined;
  /** The services it registers. */
  readonly services: readonly ServiceEntry[];
}

/** What a component needs. */
export interface Depends {
  /** The slot dependencies. */
  readonly slots: readonly SlotDependency[];
  /** The runtime ranges by tool, such as node `>=24.12`. */
  readonly runtime: Readonly<Record<string, string>>;
}

/** One validated `component.yaml`. */
export interface ComponentManifest {
  /** The component id. */
  readonly name: string;
  /** The component's own version. */
  readonly version: string;
  /** The slot it fills. */
  readonly slot: string;
  /** Its GitHub repository address, when it has one. */
  readonly repository: string | undefined;
  /** The scope it narrows its slot to, when it names one. */
  readonly scope: Scope | undefined;
  /** The contracts major the file is written against. */
  readonly contractsPin: number;
  /** Location name to a folder relative to the component root. */
  readonly locations: Readonly<Record<string, string>>;
  /** What it offers. */
  readonly provides: Provides;
  /** What it needs. */
  readonly depends: Depends;
  /** Its routes. */
  readonly routes: readonly RouteEntry[];
  /** Its hooks. */
  readonly hooks: readonly HookEntry[];
  /** Its variables. */
  readonly variables: readonly VariableDeclaration[];
  /** The ceiling of always-loaded characters per agent. */
  readonly idleCost: Readonly<Record<string, number>>;
}
